import fs from "node:fs";
import path from "node:path";
import { harnessHome, repoRoot } from "./paths.mjs";
import { loadPackageCatalog } from "./package-catalog.mjs";
import { effectiveEnabledIds, knownHarnessIds } from "./rules-render.mjs";
import { roborepoSkillsDir, roborepoStateDir } from "./state-paths.mjs";
import { slashCommandLiveDir } from "./skill-command-config.mjs";
import { runtimeAssetDestination } from "./package-harness-config.mjs";
import { listSourceSkills } from "./skill-files.mjs";

const MANAGED_SKILL_MARKER = ".roborepo-managed";
const GENERATED_COMMAND_MARKER = "Generated by scripts/build/render-slash-commands.mjs; do not edit directly.";
const LEGACY_GENERATED_COMMAND_MARKER = "Generated by scripts/build/render-skill-commands.mjs; do not edit directly.";
const OWNER_PATTERN = /Owned by package:\s*([a-z0-9][a-z0-9-]*)/;

function currentDesired(catalog = loadPackageCatalog({ includeUnavailable: true })) {
  const enabled = new Set(effectiveEnabledIds(catalog));
  const skills = new Set();
  const commands = new Map();
  const runtimeAssets = new Set();

  for (const pkg of catalog) {
    if (!enabled.has(pkg.id)) continue;
    for (const resource of pkg.resources || []) {
      if (resource.type === "skill") {
        skills.add(resource.id);
        for (const entrypoint of resource.entrypoints || []) {
          if (entrypoint.type !== "slash-command") continue;
          for (const harness of entrypoint.harnesses || []) {
            commandSet(commands, harness).add(`${pkg.id}:${entrypoint.name}.md`);
          }
        }
      } else if (resource.type === "slash-command") {
        for (const harness of resource.harnesses || []) {
          commandSet(commands, harness).add(`${pkg.id}:${resource.name}.md`);
        }
      } else if (resource.type === "runtime-asset") {
        runtimeAssets.add(runtimeAssetDestination(pkg, resource));
      }
    }
  }

  return { skills, commands, runtimeAssets };
}

function commandSet(commands, harness) {
  if (!commands.has(harness)) commands.set(harness, new Set());
  return commands.get(harness);
}

function removePath(target, label, { dryRun }) {
  if (dryRun) {
    console.log(`[dry-run] remove ${label}: ${target}`);
    return true;
  }
  fs.rmSync(target, { recursive: true, force: true });
  console.log(`removed ${label}: ${target}`);
  return true;
}

function readText(target) {
  try {
    return fs.readFileSync(target, "utf8");
  } catch {
    return null;
  }
}

function commandOwner(target) {
  const text = readText(target);
  if (!text) return null;
  if (!text.includes(GENERATED_COMMAND_MARKER) && !text.includes(LEGACY_GENERATED_COMMAND_MARKER)) return null;
  return text.match(OWNER_PATTERN)?.[1] || null;
}

function symlinkTarget(target) {
  try {
    if (!fs.lstatSync(target).isSymbolicLink()) return null;
    return fs.readlinkSync(target);
  } catch {
    return null;
  }
}

function isManagedSkillPath(target) {
  try {
    const stat = fs.lstatSync(target);
    if (stat.isSymbolicLink()) {
      const link = fs.readlinkSync(target);
      return link.startsWith(roborepoSkillsDir) || link.includes("/.roborepo/skills/");
    }
    return stat.isDirectory() && fs.existsSync(path.join(target, MANAGED_SKILL_MARKER));
  } catch {
    return false;
  }
}

function pruneSkills({ desiredSkills, removeAll, dryRun }) {
  const preservedSystemSkills = new Set(listSourceSkills(path.join(repoRoot, "globals", "system", "skills")));
  let removed = 0;

  let cacheEntries = [];
  try {
    cacheEntries = fs.readdirSync(roborepoSkillsDir, { withFileTypes: true });
  } catch {}
  for (const ent of cacheEntries) {
    const target = path.join(roborepoSkillsDir, ent.name);
    if (!isManagedSkillPath(target)) continue;
    if (!removeAll && (desiredSkills.has(ent.name) || preservedSystemSkills.has(ent.name))) continue;
    removed += removePath(target, "managed skill", { dryRun }) ? 1 : 0;
  }

  for (const harness of knownHarnessIds()) {
    const skillsDir = path.join(harnessHome[harness], "skills");
    let entries = [];
    try {
      entries = fs.readdirSync(skillsDir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      const target = path.join(skillsDir, ent.name);
      if (!isManagedSkillPath(target)) continue;
      if (!removeAll && (desiredSkills.has(ent.name) || preservedSystemSkills.has(ent.name))) continue;
      removed += removePath(target, "managed skill view", { dryRun }) ? 1 : 0;
    }
  }
  return removed;
}

function pruneCommands({ desiredCommands, removeAll, dryRun }) {
  let removed = 0;
  for (const harness of knownHarnessIds()) {
    const commandsDir = path.join(harnessHome[harness], slashCommandLiveDir(harness));
    const desired = desiredCommands.get(harness) || new Set();
    let entries = [];
    try {
      entries = fs.readdirSync(commandsDir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      if (!ent.name.endsWith(".md")) continue;
      const target = path.join(commandsDir, ent.name);
      if (symlinkTarget(target) !== null) continue;
      const owner = commandOwner(target);
      if (!owner) continue;
      if (!removeAll && desired.has(`${owner}:${ent.name}`)) continue;
      removed += removePath(target, "owned slash command", { dryRun }) ? 1 : 0;
    }
  }
  return removed;
}

function pruneRuntimeAssets({ desiredRuntimeAssets, removeAll, dryRun }) {
  const runtimeDir = path.join(roborepoStateDir, "runtime");
  let removed = 0;
  let packages = [];
  try {
    packages = fs.readdirSync(runtimeDir, { withFileTypes: true });
  } catch {
    return 0;
  }
  for (const pkgEnt of packages) {
    if (!pkgEnt.isDirectory()) continue;
    const pkgDir = path.join(runtimeDir, pkgEnt.name);
    let entries = [];
    try {
      entries = fs.readdirSync(pkgDir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const ent of entries) {
      const target = path.join(pkgDir, ent.name);
      if (!removeAll && desiredRuntimeAssets.has(target)) continue;
      removed += removePath(target, "runtime asset", { dryRun }) ? 1 : 0;
    }
    try {
      if (!dryRun && fs.existsSync(pkgDir) && fs.readdirSync(pkgDir).length === 0) fs.rmdirSync(pkgDir);
    } catch {}
  }
  return removed;
}

export function cleanupPackageProjections({ removeAll = false, dryRun = false } = {}) {
  const desired = removeAll
    ? { skills: new Set(), commands: new Map(), runtimeAssets: new Set() }
    : currentDesired();
  const removed =
    pruneCommands({ desiredCommands: desired.commands, removeAll, dryRun }) +
    pruneSkills({ desiredSkills: desired.skills, removeAll, dryRun }) +
    pruneRuntimeAssets({ desiredRuntimeAssets: desired.runtimeAssets, removeAll, dryRun });
  if (removed === 0) console.log(`package projection cleanup: no ${removeAll ? "owned" : "orphaned"} projections`);
  return { removed };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  cleanupPackageProjections({
    removeAll: process.argv.includes("--all"),
    dryRun: process.argv.includes("--dry-run"),
  });
}
