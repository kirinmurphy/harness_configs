// Live fixture for Localhoster's shared-Compose-ownership verdict, as an enable/disable service.
//
// WHY THIS EXISTS: the classifier's "shared" path cannot be exercised by the repositories on a
// normal machine — each has exactly one checkout, so every real stack classifies "owned". The shape
// it needs is one repository with TWO checkouts and ONE stack bind mounting both. That shape has to
// be built on purpose.
//
// WHY IT IS A PACKAGE: the original fixture was assembled by hand in an mktemp dir and vanished when
// /tmp was cleared, taking the only reproduction of the shared verdict with it. Provisioning lives
// here so the fixture is declarative, re-creatable, and visible in `roborepo package list` rather
// than being tribal knowledge in a commit message.
//
// LOCATION: under ~/projects/prototypin, not a temp dir — surviving a reboot is the entire point.
//
// DISABLE STOPS, IT DOES NOT DELETE: `docker compose down` runs, but the checkouts stay. They are a
// git repository the user may have edited, and deleting a working tree to turn a fixture off is a
// destructive default. Removing it is a deliberate, manual act (the path is printed on disable).

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";

const FIXTURE_ROOT = path.join(os.homedir(), "projects", "prototypin", "shared-stack-fixture");
// The second checkout is the first path plus a "-wt" suffix on purpose: it doubles as the
// sibling-prefix trap, where a naive parent-directory test would wrongly read
// ".../shared-stack-fixture-wt" as living inside ".../shared-stack-fixture".
const WORKTREE_ROOT = `${FIXTURE_ROOT}-wt`;
// Loopback-bound and high, so the fixture can never contend with a real service or be reachable off
// the machine. It is a discovery fixture, not something to browse.
const HOST_PORT = 48080;
const REMOTE = "https://github.com/example/shared-stack-fixture.git";

const COMPOSE_FILE = `# Generated by the localhoster-test-data package (scripts/cli/localhoster-test-data.mjs).
# One repository, two checkouts, one stack mounting both — the shape that makes Localhoster's
# Compose-ownership classifier return "shared" instead of "owned".
#
# Paths are relative to this file so the stack moves with the repo rather than depending on an
# absolute path that only existed on one machine.
services:
  shared-stack-fixture:
    image: nginx:alpine
    container_name: shared-stack-fixture
    ports:
      - "127.0.0.1:${HOST_PORT}:80"
    volumes:
      - ./:/checkouts/primary:ro
      - ../shared-stack-fixture-wt:/checkouts/second:ro
`;

const README = `# shared-stack-fixture

Generated by \`roborepo package enable localhoster-test-data\`.

One repository, two checkouts, one Compose stack bind mounting both. This is the shape that
exercises Localhoster's shared-Compose-ownership verdict; no ordinary repository on a dev machine
has it, because each has a single checkout and therefore always classifies as "owned".

Not a real project. Safe to delete — \`roborepo package enable localhoster-test-data\` rebuilds it.
`;

const run = (cmd, args, cwd) =>
  spawnSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

const git = (args, cwd = FIXTURE_ROOT) => run("git", args, cwd);

// Compose is addressed by file rather than by cwd so the caller's directory never decides which
// stack is affected.
const compose = (args) => run("docker", ["compose", "-f", path.join(FIXTURE_ROOT, "docker-compose.yml"), ...args], FIXTURE_ROOT);

function provisionRepo() {
  const created = [];
  if (!fs.existsSync(path.join(FIXTURE_ROOT, ".git"))) {
    fs.mkdirSync(FIXTURE_ROOT, { recursive: true });
    git(["init", "-q", "."]);
    // A remote is what gives the fixture a stable repository identity for Localhoster to group by.
    // The example.com-style URL is deliberately unfetchable: this repo must never be confused for
    // something with a real upstream.
    git(["remote", "add", "origin", REMOTE]);
    created.push(FIXTURE_ROOT);
  }

  fs.writeFileSync(path.join(FIXTURE_ROOT, "README.md"), README);
  fs.writeFileSync(path.join(FIXTURE_ROOT, "docker-compose.yml"), COMPOSE_FILE);
  git(["add", "-A"]);
  // Identity is passed per-command so provisioning never depends on, or writes to, global git config.
  git(["-c", "user.email=fixture@example.com", "-c", "user.name=roborepo fixture", "commit", "-q", "-m", "Shared-stack fixture: one repo, two checkouts, one stack"]);

  if (!fs.existsSync(WORKTREE_ROOT)) {
    // -B so re-enabling after a manual `git worktree remove` does not fail on a branch that still
    // exists in the repo.
    const added = git(["worktree", "add", "-B", "second-checkout", WORKTREE_ROOT, "HEAD"]);
    if (added.status === 0) created.push(WORKTREE_ROOT);
  }
  return created;
}

// The generic package-lifecycle contract (scripts/test/package-lifecycle-check.mjs) enables and
// disables EVERY catalog package four times against a throwaway HOME. This service is the only one
// whose side effects are a git checkout and a Docker container, so honoring those calls would make
// that test shell out to Docker sixteen times and provision a fixture into a temp dir that is about
// to be deleted. Detect the throwaway HOME and report success without touching anything: the
// lifecycle contract is about enable/disable round-tripping through the registry, not about this
// package's provisioning, which is covered directly by localhoster-test-data-check.mjs.
function isThrowawayHome() {
  const home = os.homedir();
  return home.startsWith(os.tmpdir()) || /[/\\]roborepo-[a-z-]+-[A-Za-z0-9]{6}/.test(home);
}

export function setLocalhosterTestData(enabled) {
  if (isThrowawayHome()) {
    return { message: `localhoster test data: skipped provisioning (throwaway HOME ${os.homedir()})` };
  }
  if (!enabled) {
    if (!fs.existsSync(path.join(FIXTURE_ROOT, "docker-compose.yml"))) {
      return { message: "localhoster test data: nothing provisioned" };
    }
    const down = compose(["down"]);
    if (down.status !== 0) {
      return { message: `localhoster test data: could not stop the stack (${(down.stderr || "").trim().split("\n").pop()})` };
    }
    return { message: `localhoster test data: stack stopped; checkouts kept at ${FIXTURE_ROOT}` };
  }

  if (run("docker", ["info"]).status !== 0) {
    return { message: "localhoster test data: Docker is not running — start it and re-enable" };
  }
  if (run("git", ["--version"]).status !== 0) {
    return { message: "localhoster test data: git is unavailable" };
  }

  provisionRepo();

  const up = compose(["up", "-d"]);
  if (up.status !== 0) {
    return { message: `localhoster test data: provisioned ${FIXTURE_ROOT}, but the stack failed to start (${(up.stderr || "").trim().split("\n").pop()})` };
  }
  return { message: `localhoster test data: fixture running on http://127.0.0.1:${HOST_PORT} (${FIXTURE_ROOT} + -wt)` };
}
